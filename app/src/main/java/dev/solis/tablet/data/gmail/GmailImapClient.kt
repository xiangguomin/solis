package dev.solis.tablet.data.gmail

import android.util.Base64
import android.util.Log
import java.io.BufferedReader
import java.io.InputStreamReader
import java.io.OutputStreamWriter
import java.io.PrintWriter
import java.nio.charset.Charset
import javax.net.ssl.SSLSocket
import javax.net.ssl.SSLSocketFactory

/**
 * Connects to `imap.gmail.com:993` and specifically looks for the user's daily Spark/Gemini
 * `"Daily Email Digest"` email first, parsing its `⚡ Action Items & Deadlines` and top bullets
 * into clean, concise dashboard cards (with full sub-bullets available on tap).
 */
class GmailImapClient {

    data class ImapEmailMessage(
        val uid: String,
        val from: String,
        val subject: String,
        val dateText: String,
        val bodySnippet: String
    )

    /**
     * Fetches and parses the latest `"Daily Email Digest"` generated by Gemini/Spark in the user's
     * inbox into concise, scannable `GmailDigestItem` cards.
     */
    fun fetchParsedDailyDigestItems(
        emailAddress: String,
        appPassword: String
    ): List<GmailDigestItem> {
        val cleanEmail = emailAddress.trim()
        val cleanPass = appPassword.replace(" ", "").trim()
        if (cleanEmail.isEmpty() || cleanPass.isEmpty()) return emptyList()

        val socket = SSLSocketFactory.getDefault()
            .createSocket("imap.gmail.com", 993) as SSLSocket
        socket.soTimeout = 15_000

        return socket.use { ssl ->
            val reader = BufferedReader(InputStreamReader(ssl.inputStream, Charsets.UTF_8))
            val writer = PrintWriter(OutputStreamWriter(ssl.outputStream, Charsets.UTF_8), true)

            reader.readLine() // greeting

            val loginResp = sendCommand(writer, reader, "A01", "LOGIN \"$cleanEmail\" \"$cleanPass\"")
            if (loginResp.none { it.startsWith("A01 OK") }) {
                Log.w("SolisImap", "IMAP Login failed for $cleanEmail")
                return@use emptyList()
            }

            sendCommand(writer, reader, "A02", "EXAMINE INBOX")

            // 1. Search specifically for the user's Spark/Gemini "Daily Email Digest"
            val digestSearch = sendCommand(
                writer,
                reader,
                "A03",
                "UID SEARCH X-GM-RAW \"subject:\\\"Daily Email Digest\\\" newer_than:7d\""
            )
            val digestUids = parseSearchUids(digestSearch)

            if (digestUids.isNotEmpty()) {
                val latestDigestUid = digestUids.last()
                val rawLines = sendCommand(
                    writer,
                    reader,
                    "D01",
                    "UID FETCH $latestDigestUid (BODY.PEEK[HEADER.FIELDS (SUBJECT DATE)] BODY.PEEK[1])"
                )
                val parsedDigest = parseSparkDailyDigestEmail(latestDigestUid, rawLines)
                if (parsedDigest.isNotEmpty()) {
                    sendCommand(writer, reader, "A99", "LOGOUT")
                    return@use parsedDigest
                }
            }

            // 2. Fallback if no Daily Email Digest found
            val fallbackLines = sendCommand(
                writer,
                reader,
                "A04",
                "UID SEARCH X-GM-RAW \"newer_than:2d is:important -category:promotions -category:social -category:forums -from:no-reply@accounts.google.com\""
            )
            val uids = parseSearchUids(fallbackLines).takeLast(5).reversed()
            val items = mutableListOf<GmailDigestItem>()
            uids.forEachIndexed { idx, uid ->
                val fetchLines = sendCommand(
                    writer,
                    reader,
                    "F$idx",
                    "UID FETCH $uid (BODY.PEEK[HEADER.FIELDS (FROM SUBJECT DATE)] BODY.PEEK[TEXT]<0.500>)"
                )
                parseFetchedEmail(uid, fetchLines)?.let { msg ->
                    if (!isFinancialOrStatementItem(msg.subject, "${msg.from} ${msg.bodySnippet}")) {
                        val senderShort = msg.from.substringBefore("<").trim().removeSurrounding("\"")
                            .ifEmpty { "Gmail" }
                        items.add(
                            GmailDigestItem(
                                threadId = msg.uid,
                                category = GmailDigestRepository.inferCategory(msg.subject),
                                senderName = senderShort,
                                summaryOneLiner = msg.subject,
                                receivedTimeText = msg.dateText,
                                subject = msg.subject,
                                senderEmail = msg.from,
                                fullBodySnippet = msg.bodySnippet
                            )
                        )
                    }
                }
            }

            sendCommand(writer, reader, "A99", "LOGOUT")
            items
        }
    }

    /**
     * Parses the structured plain-text body of `"Daily Email Digest - <Date>"` into
     * 5–6 ultra-clean, scannable action/topic items where:
     * - `senderName` = Short Topic / School / Org (e.g. `Quicksilver Swim`, `Cub Scouts Pack 274`, `Graystone Elem`)
     * - `summaryOneLiner` = Concise 1-line summary that fits cleanly on the dashboard card
     * - `fullBodySnippet` = Complete sub-bullets & links (with ugly Google redirect wrappers stripped)
     *   shown when the user taps the item!
     */
    private fun parseSparkDailyDigestEmail(
        uid: String,
        lines: List<String>
    ): List<GmailDigestItem> {
        var digestDateLabel = "Today's Digest"
        val rawBodyBuilder = StringBuilder()
        var inBody = false

        for (line in lines) {
            if (line.startsWith("* ") && line.contains("FETCH (")) continue
            if (line.startsWith("D01 ") && (line.contains("OK") || line.contains("NO"))) continue
            if (line == ")") continue

            if (!inBody) {
                if (line.startsWith("Subject:", ignoreCase = true)) {
                    val subj = decodeMimeHeader(line.substringAfter(":").trim())
                    digestDateLabel = subj.substringAfter("Daily Email Digest - ", "Today").trim()
                } else if (line.contains("BODY[1]")) {
                    inBody = true
                }
            } else {
                rawBodyBuilder.appendLine(line)
            }
        }

        val decodedBody = cleanUrls(decodeQuotedPrintable(rawBodyBuilder.toString()))
        if (decodedBody.isBlank()) return emptyList()

        // Extract top-level `* Topic:` blocks from the Action Items section (before the first `---` divider)
        // and all other important section bullets after it so the user can scroll through all of them
        val actionSection = decodedBody.substringBefore("----").ifBlank { decodedBody }
        val items = parseBulletBlocks(uid, actionSection, digestDateLabel, isActionSection = true)
            .toMutableList()

        if (decodedBody.contains("----")) {
            val restSections = decodedBody.substringAfter("----")
            val extra = parseBulletBlocks(uid, restSections, digestDateLabel, isActionSection = false)
            for (e in extra) {
                if (items.none { it.senderName.equals(e.senderName, ignoreCase = true) && it.summaryOneLiner == e.summaryOneLiner }) {
                    items.add(e)
                }
            }
        }

        return items
    }

    private fun parseBulletBlocks(
        uid: String,
        sectionText: String,
        dateLabel: String,
        isActionSection: Boolean
    ): List<GmailDigestItem> {
        val results = mutableListOf<GmailDigestItem>()
        var currentTitle = ""
        val currentSubBullets = mutableListOf<String>()

        fun flushCurrent() {
            if (currentTitle.isBlank()) return
            val cleanTitle = currentTitle.removeSuffix(":").trim()
            val fullDetails = buildString {
                appendLine("• $cleanTitle")
                currentSubBullets.forEach { sub ->
                    appendLine("  – $sub")
                }
            }.trim()

            // Skip bank/credit card statements, bills, and payment notifications
            if (isFinancialOrStatementItem(cleanTitle, fullDetails)) {
                currentTitle = ""
                currentSubBullets.clear()
                return
            }

            // Build a short, punchy 1-line takeaway (keep full details in fullBodySnippet for tap modal)
            val cleanTopic = cleanTitle
                .replace(Regex("""\s*\([^)]*\)\s*"""), " ")
                .replace("  ", " ")
                .trim()
                .take(32)

            val parenthesizedHint = Regex("""\(([^)]+)\)""").find(cleanTitle)?.groupValues?.get(1)
            val topicWithHint = if (!parenthesizedHint.isNullOrBlank() && parenthesizedHint.length <= 18) {
                "$cleanTopic ($parenthesizedHint)"
            } else {
                cleanTopic
            }

            // Take ONLY the first sub-bullet's core point so it's never a wall of text
            val conciseTakeaway = currentSubBullets.firstOrNull()
                ?.replace(Regex("""https?://\S+"""), "")
                ?.replace(Regex("""\s+"""), " ")
                ?.trim()
                ?.trimEnd('-', ':', ' ')
                ?.let { firstSub ->
                    // Strip redundant lead label if it repeats the topic
                    val afterColon = firstSub.substringAfter(": ", "")
                    val core = if (afterColon.isNotEmpty() && firstSub.substringBefore(": ").length < 28) {
                        firstSub
                    } else {
                        firstSub
                    }
                    if (core.length > 95) core.take(92).trimEnd() + "…" else core
                }
                ?: cleanTitle

            val category = when {
                isActionSection -> DigestCategory.ACTION_REQUIRED
                "Delivery" in "$cleanTitle $conciseTakeaway" ||
                    "Package" in "$cleanTitle $conciseTakeaway" ||
                    "Amazon" in "$cleanTitle $conciseTakeaway" -> DigestCategory.DELIVERY
                else -> DigestCategory.PERSONAL
            }

            results.add(
                GmailDigestItem(
                    threadId = "$uid-${ if (isActionSection) "act" else "sec" }-${results.size}",
                    category = category,
                    senderName = topicWithHint.ifEmpty { "Update" },
                    summaryOneLiner = conciseTakeaway,
                    receivedTimeText = dateLabel,
                    subject = cleanTitle,
                    senderEmail = "Daily Email Digest",
                    fullBodySnippet = fullDetails
                )
            )
            currentTitle = ""
            currentSubBullets.clear()
        }

        for (rawLine in sectionText.lines()) {
            val trimmed = rawLine.trim()
            when {
                trimmed.startsWith("* ") -> {
                    flushCurrent()
                    currentTitle = trimmed.removePrefix("* ").trim()
                }
                trimmed.startsWith("- ") && currentTitle.isNotEmpty() -> {
                    currentSubBullets.add(trimmed.removePrefix("- ").trim())
                }
                currentSubBullets.isNotEmpty() && trimmed.isNotEmpty() &&
                    !trimmed.startsWith("⚡") && !trimmed.startsWith("---") -> {
                    // Continuation of previous sub-bullet line
                    val lastIdx = currentSubBullets.lastIndex
                    currentSubBullets[lastIdx] = "${currentSubBullets[lastIdx]} $trimmed"
                }
            }
        }
        flushCurrent()
        return results
    }

    /**
     * Filters out bank/credit card statements, bills, AutoPay alerts, and financial reports.
     */
    private fun isFinancialOrStatementItem(title: String, details: String): Boolean {
        val text = "$title $details".lowercase()
        val keywords = listOf(
            "statement",
            "bills, statements",
            "credit card",
            "target circle card",
            "american express",
            "chase",
            "autopay",
            "payment due",
            "minimum payment",
            "statement balance",
            "cash app",
            "bank of america",
            "wells fargo",
            "citibank",
            "capital one"
        )
        return keywords.any { it in text }
    }

    /**
     * Decodes Quoted-Printable soft line breaks (`=\r\n`) and hex sequences (`=E2=9A=A1`).
     */
    private fun decodeQuotedPrintable(input: String): String {
        val unfolded = input.replace("=\r\n", "").replace("=\n", "")
        val out = java.io.ByteArrayOutputStream()
        var i = 0
        while (i < unfolded.length) {
            val c = unfolded[i]
            if (c == '=' && i + 2 < unfolded.length) {
                val hex = unfolded.substring(i + 1, i + 3)
                val byteVal = hex.toIntOrNull(16)
                if (byteVal != null) {
                    out.write(byteVal)
                    i += 3
                    continue
                }
            }
            out.write(c.code)
            i++
        }
        return String(out.toByteArray(), Charsets.UTF_8)
    }

    /**
     * Replaces long `https://www.google.com/url?q=https://members.pack274.org&source=gmail...`
     * redirect wrappers with the clean destination URL.
     */
    private fun cleanUrls(text: String): String {
        val googleRedirect = Regex("""https://www\.google\.com/url\?q=([^&\s]+)&[^\s)]+""")
        return googleRedirect.replace(text) { match ->
            java.net.URLDecoder.decode(match.groupValues[1], "UTF-8")
        }
    }

    private fun sendCommand(
        writer: PrintWriter,
        reader: BufferedReader,
        tag: String,
        command: String
    ): List<String> {
        writer.print("$tag $command\r\n")
        writer.flush()
        val lines = mutableListOf<String>()
        while (true) {
            val line = reader.readLine() ?: break
            lines.add(line)
            if (line.startsWith("$tag OK") || line.startsWith("$tag NO") || line.startsWith("$tag BAD")) {
                break
            }
        }
        return lines
    }

    private fun parseSearchUids(lines: List<String>): List<String> {
        val searchLine = lines.firstOrNull { it.startsWith("* SEARCH") } ?: return emptyList()
        return searchLine.removePrefix("* SEARCH").trim()
            .split(" ")
            .map { it.trim() }
            .filter { it.isNotEmpty() && it.all(Char::isDigit) }
    }

    private fun parseFetchedEmail(uid: String, lines: List<String>): ImapEmailMessage? {
        var from = ""
        var subject = ""
        var dateText = ""
        val bodyLines = mutableListOf<String>()
        var inHeaders = true

        for (line in lines) {
            if (line.startsWith("* ") && line.contains("FETCH (")) continue
            if (line.startsWith("F") && (line.contains(" OK ") || line.contains(" NO "))) continue
            if (line == ")") continue

            if (inHeaders) {
                when {
                    line.startsWith("From:", ignoreCase = true) ->
                        from = decodeMimeHeader(line.substringAfter(":").trim())
                    line.startsWith("Subject:", ignoreCase = true) ->
                        subject = decodeMimeHeader(line.substringAfter(":").trim())
                    line.startsWith("Date:", ignoreCase = true) ->
                        dateText = line.substringAfter(":").trim().take(16)
                    line.contains("BODY[TEXT]") -> inHeaders = false
                }
            } else {
                if (!line.startsWith("--") && !line.startsWith("Content-")) {
                    val cleaned = line.replace(Regex("<[^>]*>"), " ").trim()
                    if (cleaned.isNotEmpty()) bodyLines.add(cleaned)
                }
            }
        }

        if (from.isEmpty() && subject.isEmpty()) return null
        val snippet = bodyLines.joinToString("\n").take(500).ifBlank { subject }
        return ImapEmailMessage(
            uid = uid,
            from = from,
            subject = subject.ifBlank { "(No Subject)" },
            dateText = dateText.ifBlank { "Recent" },
            bodySnippet = snippet
        )
    }

    private fun decodeMimeHeader(raw: String): String {
        if (!raw.contains("=?")) return raw
        return runCatching {
            val regex = Regex("""=\?([^?]+)\?([BbQq])\?([^?]+)\?=""")
            regex.replace(raw) { match ->
                val charset = match.groupValues[1]
                val encoding = match.groupValues[2].uppercase()
                val text = match.groupValues[3]
                if (encoding == "B") {
                    val bytes = Base64.decode(text, Base64.DEFAULT)
                    String(bytes, Charset.forName(charset))
                } else {
                    text.replace("_", " ")
                }
            }
        }.getOrDefault(raw)
    }
}
